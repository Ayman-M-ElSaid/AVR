#define FONT_CHAR_WIDTH 5u
#define FONT_CHAR_SPACING 1u                                   /* blank column appended after each glyph    */
#define FONT_TOTAL_WIDTH (FONT_CHAR_WIDTH + FONT_CHAR_SPACING) /* = 6     */

static void I2C_start(uint8_t address)
{
    TWCR = (1 << TWINT) | (1 << TWSTA) | (1 << TWEN);
    while (!(TWCR & (1 << TWINT)))
        ;

    TWDR = address << 1;
    TWCR = (1 << TWINT) | (1 << TWEN);
    while (!(TWCR & (1 << TWINT)))
        ;

    if ((TWSR & 0xF8) != 0x18)
        return;
}

static void I2C_stop(void)
{
    TWCR = (1 << TWSTO) | (1 << TWINT) | (1 << TWEN);
    _delay_us(10);
}

static void I2C_write_byte(uint8_t byte)
{
    TWDR = byte;
    TWCR = (1 << TWINT) | (1 << TWEN);
    while (!(TWCR & (1 << TWINT)))
        ;
}

static void oled_set_position(OLED *oled, uint8_t page, uint8_t col)
{
    oled_command(oled, 0xB0 | (page & 0x07));
    oled_command(oled, 0x00 | (col & 0x0F));
    oled_command(oled, 0x10 | (col >> 4));
}

static void oled_send_data(OLED *oled, uint8_t byte)
{
    I2C_start(oled->address);
    I2C_write_byte(0x40);
    I2C_write_byte(byte);
    I2C_stop();
}

void oled_init(OLED *oled, uint8_t address)
{
    oled->address = address;
    _delay_ms(200);

    TWSR = 0x00;
    TWBR = F_CPU > 100000UL ? 32 : 2;
    TWCR = 1 << TWEN;

    for (uint8_t i = 0; i < sizeof(OLED_INIT_SEQ); i++)
    {
        oled_command(oled, pgm_read_byte(&OLED_INIT_SEQ[i]));
    }

    oled_clear(oled);
}

void oled_command(OLED *oled, uint8_t cmd)
{
    I2C_start(oled->address);
    I2C_write_byte(0x00);
    I2C_write_byte(cmd);
    I2C_stop();
}

void oled_write_char(OLED *oled, uint8_t page, uint8_t col, char c)
{
    oled_set_position(oled, page, col);
    const uint8_t *glyph = FONT_5X7[(uint8_t)(c - 0x20)];
    for (uint8_t i = 0; i < FONT_CHAR_WIDTH; i++)
    {
        oled_send_data(oled, pgm_read_byte(&glyph[i]));
    }
    // Send the blank spacing column — separates adjacent characters
    oled_send_data(oled, 0x00);
}

void oled_write_string(OLED *oled, uint8_t page, uint8_t col, const char *string)
{
    while (*string)
    {
        oled_write_char(oled, page, col, *string++);
        col += FONT_TOTAL_WIDTH; /* advance column by one character width  */
    }
}

void oled_clear(OLED *oled)
{
    for (uint8_t page = 0; page < OLED_PAGES; page++)
    {
        oled_set_position(oled, page, 0);
        for (uint8_t col = 0; col < OLED_WIDTH; col++)
        {
            oled_send_data(oled, 0x00);
        }
    }
}

void oled_clear_page(OLED *oled, uint8_t page)
{
    if (page >= OLED_PAGES)
        return;
    oled_set_position(oled, page, 0);
    for (uint8_t col = 0; col < OLED_WIDTH; col++)
    {
        oled_send_data(oled, 0x00);
    }
}

void oled_draw_bitmap(OLED *oled, uint8_t page, uint8_t col, uint8_t width, uint8_t height, const uint8_t *bitmap)
{
    
    oled_command(oled, 0x20);
    oled_command(oled, 0x02); 
    uint8_t height_pages=height/8;
    for (uint8_t p = 0; p < height_pages; p++) {
        uint8_t current_page = page + p;
        uint8_t current_col  = col;

        oled_command(oled, 0xB0 | current_page);

        oled_command(oled, 0x00 | (current_col & 0x0F));
        oled_command(oled, 0x10 | ((current_col >> 4) & 0x0F));

        for (uint8_t c = 0; c < width; c++) {
            oled_send_data(oled, pgm_read_byte(&bitmap[p * width + c]));
        }
    }
}

